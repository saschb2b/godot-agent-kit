GENERATED_LICENSE = "generated by godot-agent; owned by the project"


def _out_dir(project: Path, label: str) -> Path:
    path = CACHE_DIR / "assets" / project_name(project) / f"{datetime.now():%Y%m%d-%H%M%S}-{label}"
    path.mkdir(parents=True, exist_ok=True)
    return path


def godot_import(project: Path) -> None:
    """Lets Godot import new files (.import, .uid) so scenes and resources can use them."""
    subprocess.run([find_godot(), "--headless", "--path", str(project), "--import"],
                   capture_output=True, timeout=900)


def _verify_load(project: Path, rels: list[str]) -> list[str]:
    result = check_project(project, refresh=False, only=[f"res://{r}" for r in rels])
    return [f"{e['file'] or 'engine'}:{e['line']} {e['message']}" for e in result["errors"]] + \
        [f"Godot failed to load {f}" for f in result["failed_files"]]


# ── init ──

def init_style(project_dir: str, out: str | None = None, force: bool = False) -> dict:
    """Drafts asset_style.json from the assets a project already has.

    Each folder gets a rule describing what its files have in common (size,
    frame grid, alpha, palette, loudness), so new files that break the pattern
    stand out. The draft is a starting point to tighten by hand.
    """
    project = resolve_project(project_dir)
    target = Path(out).expanduser() if out else project / STYLE_FILE
    if target.exists() and not force:
        raise GodotAgentError(f"{target} exists; pass --force to overwrite")
    palette_dir = target.parent / "palettes"
    by_dir: dict[str, list[str]] = collections.defaultdict(list)
    for rel in iter_assets(project):
        by_dir[str(Path(rel).parent)].append(rel)

    rules: list[dict] = []
    palettes: dict[str, str] = {}
    import_votes: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    folder_palettes: dict[str, list] = {}
    image_rules: dict[str, dict] = {}
    for folder, rels in sorted(by_dir.items()):
        image_files = [r for r in rels if kind_of(r) == "image"]
        audio_files = [r for r in rels if kind_of(r) == "audio"]
        if image_files:
            rule, palette = _image_group_rule(project, folder, image_files, import_votes)
            if palette:
                folder_palettes[folder] = palette
            exts = sorted({Path(r).suffix.lstrip(".") for r in image_files})
            pattern = f"{folder}/*.{exts[0]}" if len(exts) == 1 else f"{folder}/*.{{{','.join(exts)}}}"
            image_rules[folder] = rule
            rules.append({"match": pattern, "image": rule, "files": len(image_files)})
        if audio_files:
            rules.append({"match": f"{folder}/*", "audio": _audio_group_rule(project, folder, audio_files),
                          "files": len(audio_files)})

    # Sibling folders (one per animation of a character, say) usually share one
    # palette; give them a single palette file when their colors fit together.
    by_parent: dict[str, list[str]] = collections.defaultdict(list)
    for folder in folder_palettes:
        by_parent[str(Path(folder).parent)].append(folder)
    for parent, siblings in sorted(by_parent.items()):
        union = set().union(*(set(folder_palettes[f]) for f in siblings))
        groups = [(parent, siblings, union)] if len(siblings) > 1 and len(union) <= 64 \
            else [(f, [f], set(folder_palettes[f])) for f in siblings]
        for owner, members, colors in groups:
            slug = re.sub(r"[^A-Za-z0-9]+", "_", owner).strip("_").lower()
            # A folder with its own images and merged subfolders would otherwise
            # write two palettes under one name.
            if len(members) > 1 and owner in folder_palettes:
                slug += "_shared"
            palette_file = palette_dir / f"{slug}.gpl"
            write_palette(palette_file, slug, sorted(colors, key=lambda c: (images.luminance(c), c)))
            palettes[slug] = rel_path(project, palette_file) if palette_file.is_relative_to(project) \
                else str(palette_file)
            for member in members:
                image_rules[member]["palette"] = slug

    general = {key: votes.most_common(1)[0][0] for key, votes in import_votes.items()}
    head = [{"match": "**/*.png", "image": {"import": general}}] if general else []
    style = {"version": 1, "background": default_background(project), "palettes": palettes,
             "ignore": [], "rules": head + rules}
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(style, indent=2) + "\n")
    return {"style": str(target), "rules": len(style["rules"]), "palettes": len(palettes)}


def _image_group_rule(project: Path, folder: str, rels: list[str], import_votes: dict) -> tuple[dict, list]:
    metrics = [images.analyze_image(project / r) for r in rels]
    sizes = collections.Counter(tuple(m["size"]) for m in metrics)
    rule: dict = {}
    top_size, top_count = sizes.most_common(1)[0]
    if top_count / len(rels) >= 0.8 and len(rels) >= 2:
        rule["size"] = list(top_size)
    else:
        grid = 0
        for w, h in sizes:
            grid = math.gcd(grid, math.gcd(w, h))
        heights = {h for _, h in sizes}
        if len(heights) == 1 and all(w % next(iter(heights)) == 0 for w, _ in sizes):
            # One row of square frames per file: an animation strip.
            frame = next(iter(heights))
            rule["frame"] = [frame, frame]
            jitters = [images.analyze_image(project / r, (frame, frame)).get("baseline_jitter", 0) for r in rels]
            rule["max_baseline_jitter"] = max(jitters)
        elif grid >= 8:
            rule["multiple_of"] = [grid, grid]
    if sum(1 for m in metrics if m["semi_transparent_pixels"] == 0) / len(metrics) >= 0.9:
        rule["binary_alpha"] = True
    palette: list = []
    if max(m["colors"] for m in metrics) <= 64:
        union: set = set()
        for r in rels:
            with images.Image.open(project / r) as img:
                union |= {c[:3] for _, c in images._opaque_colors(img.convert("RGBA"))}
        if len(union) <= 64:
            palette = sorted(union, key=lambda c: (images.luminance(c), c))
            rule["max_colors"] = max(m["colors"] for m in metrics)
    contrasts = []
    background = images.hex_to_rgb(default_background(project))
    for m in metrics:
        if m.get("edge_color"):
            contrasts.append(images.contrast_ratio(m["edge_color"], background))
    if contrasts:
        # The weakest existing sprite sets the floor, so new art cannot read worse.
        rule["min_silhouette_contrast"] = math.floor(min(contrasts) * 10) / 10
    for r in rels:
        for key, value in (images.read_import_params(project / r) or {}).items():
            if key in ("compress/mode", "mipmaps/generate"):
                import_votes[key][value] += 1
    return rule, palette


def _level_band(values: list[float]) -> list[float]:
    if len(values) < 3:
        return [round(min(values) - 3, 1), round(max(values) + 3, 1)]
    deciles = statistics.quantiles(values, n=10)
    return [round(deciles[0] - 3, 1), round(deciles[-1] + 3, 1)]


def _audio_group_rule(project: Path, folder: str, rels: list[str]) -> dict:
    looping = any(word in folder.lower() for word in ("bgm", "music", "loop", "ambience"))
    metrics = [audio.analyze_audio(project / r) for r in rels]
    rule: dict = {"max_peak_db": -0.3, "max_leading_silence_ms": 50 if not looping else 250}
    rates = sorted({m["sample_rate"] for m in metrics if m.get("sample_rate")})
    if rates:
        rule["sample_rates"] = rates
    lufs = [m["loudness_lufs"] for m in metrics if m.get("loudness_lufs") is not None]
    rms = [m["rms_db"] for m in metrics if m.get("rms_db") is not None and m.get("loudness_lufs") is None]
    # Files in one folder should sit at a similar level. The 10th to 90th
    # percentile, widened by 3 dB, flags only the ones that jump out of the mix.
    if lufs:
        rule["loudness_lufs"] = _level_band(lufs)
    if rms:
        rule["rms_db"] = _level_band(rms)
    if looping:
        rule["loop"] = True
    else:
        rule["max_duration_s"] = round(max(m.get("duration_s", 0) for m in metrics) + 0.5, 1)
    return rule


# ── check ──

def check_assets(project_dir: str, paths: list[str] | None = None, style_path: str | None = None,
                 review: bool = False) -> dict:
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    started = time.monotonic()
    results, unruled = [], 0
    for rel in iter_assets(project, paths):
        if style.ignored(rel):
            continue
        kind = kind_of(rel)
        rule = style.rule_for(rel, kind)
        if not rule:
            unruled += 1
            continue
        try:
            if kind == "image":
                results.append(images.validate_image(project, rel, rule, style))
            else:
                results.append(audio.validate_audio(project, rel, rule))
        except (OSError, ValueError) as exc:
            results.append({"path": rel, "kind": kind, "ok": False, "problems": [f"unreadable: {exc}"],
                            "notes": [], "metrics": {}})
    report = {
        "project": str(project), "style": str(style.source) if style.source else None,
        "checked": len(results), "failed": sum(1 for r in results if not r["ok"]),
        "without_rule": unruled, "duration_s": round(time.monotonic() - started, 2), "results": results,
    }
    if style.source is None:
        report["note"] = f"no {STYLE_FILE}; run `godot-agent asset init` to draft one"
    if review and results:
        shown = [r for r in results if r["kind"] == "image"]
        shown.sort(key=lambda r: r["ok"])  # failures first
        if shown:
            out = _out_dir(project, "review") / "review.png"
            report["review_sheet"] = str(images.review_sheet(shown, project, out, style.background))
    return report


def _category(problem: str) -> str:
    """'37 colors, max 16' -> 'colors'; 'size 16x32, expected 16x16' -> 'size'."""
    for word in re.findall(r"[a-z][a-z-]+", problem.lower()):
        if word not in ("expected", "max", "min", "single", "pixels"):
            return word
    return "other"


def format_check(report: dict, limit: int = 40) -> str:
    lines = [f"godot-agent asset check: {report['checked'] - report['failed']}/{report['checked']} pass"
             f" · {report['without_rule']} without a rule · {report['duration_s']}s"]
    if report.get("note"):
        lines.append(f"  note: {report['note']}")
    failing = [r for r in report["results"] if not r["ok"]]
    for r in failing[:limit]:
        lines.append(f"  FAIL  {r['path']}")
        lines += [f"        {p}" for p in r["problems"][:4]]
    if len(failing) > limit:
        lines.append(f"  ... {len(failing) - limit} more failures (use --json)")
    problem_kinds = collections.Counter(_category(p) for r in failing for p in r["problems"])
    if len(failing) > 3:
        lines.append("  most common: " + ", ".join(f"{k} ×{n}" for k, n in problem_kinds.most_common(5)))
    if report.get("review_sheet"):
        lines.append(f"  review: {report['review_sheet']}")
    return "\n".join(lines)


# ── conform ──

def conform(project_dir: str, source: str, dest: str, style_path: str | None = None, *,
            size: list[int] | None = None, anchor: str = "center", resample: str = "box",
            outline: str | None = None, clean: bool = False, trim: bool = True,
            import_into_godot: bool = True, record: bool = True) -> dict:
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    src = Path(source).expanduser().resolve()
    if not src.exists():
        raise GodotAgentError(f"No image at {src}")
    rel = rel_path(project, dest)
    rule = style.rule_for(rel, "image")
    steps = images.conform_image(src, project / rel, rule, style, size=tuple(size) if size else None,
                                 anchor=anchor, resample=resample, outline=outline, clean=clean, trim=trim)
    options = {"size": size, "anchor": anchor, "resample": resample, "outline": outline, "clean": clean, "trim": trim}
    if record:
        manifest.record(project, rel, {"tool": "conform", "source": str(src), "options": options,
                                       "license": "same as source"})
    if import_into_godot:
        godot_import(project)
    report = images.validate_image(project, rel, rule, style)
    report["steps"] = steps
    out = _out_dir(project, "conform")
    before_after = out / "before_after.png"
    images.review_sheet([{"path": str(src), "ok": True}, {"path": rel, "ok": report["ok"]}], project,
                        before_after, style.background, tile=192)
    report["preview"] = str(before_after)
    return report


# ── Aseprite ──

def import_aseprite(project_dir: str, source: str, dest: str, style_path: str | None = None,
                    import_into_godot: bool = True, record: bool = True) -> dict:
    """foo.aseprite -> dest.png (packed sheet) + dest.tres (SpriteFrames, one animation per tag)."""
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    src = Path(source).expanduser().resolve()
    base = rel_path(project, dest)
    base = base[: -len(Path(base).suffix)] if Path(base).suffix in (".png", ".tres") else base
    sheet_rel, frames_rel = f"{base}.png", f"{base}.tres"
    data = aseprite.export_sheet(src, project / sheet_rel)
    animations = aseprite.write_sprite_frames(project / frames_rel, f"res://{sheet_rel}", data)
    if record:
        for rel in (sheet_rel, frames_rel):
            manifest.record(project, rel, {"tool": "aseprite", "source": str(src), "dest": base,
                                           "license": "same as source"})
    report = images.validate_image(project, sheet_rel, style.rule_for(sheet_rel, "image"), style)
    report["frames_resource"] = frames_rel
    report["animations"] = [{"name": a["name"], "frames": len(a["frames"]), "fps": a["speed"], "loop": a["loop"]}
                            for a in animations]
    if import_into_godot:
        godot_import(project)
        if load_errors := _verify_load(project, [sheet_rel, frames_rel]):
            report["ok"] = False
            report["problems"] += load_errors
    return report


# ── SFX ──

def make_sfx(project_dir: str, preset: str, dest: str, seed: int = 1, variants: int = 1,
             peak_db: float = -1.0, mutate_amount: float = 0.0, params: dict | None = None,
             style_path: str | None = None, import_into_godot: bool = True, record: bool = True) -> dict:
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    rel = rel_path(project, dest)
    stem, suffix = rel[: -len(Path(rel).suffix)] if Path(rel).suffix else rel, ".wav"
    results = []
    for n in range(variants):
        variant_seed = seed + n
        out_rel = f"{stem}{suffix}" if variants == 1 else f"{stem}_{n + 1}{suffix}"
        recipe = dict(params) if params else audio.preset_params(preset, variant_seed)
        if mutate_amount:
            recipe = audio.mutate(recipe, mutate_amount, variant_seed)
        audio.write_wav(audio.synthesize(recipe), project / out_rel, peak_db=peak_db)
        if record:
            manifest.record(project, out_rel, {"tool": "sfx", "preset": preset, "seed": variant_seed,
                                               "peak_db": peak_db, "params": recipe, "license": GENERATED_LICENSE})
        result = audio.validate_audio(project, out_rel, style.rule_for(out_rel, "audio"))
        result["seed"] = variant_seed
        results.append(result)
    if import_into_godot:
        godot_import(project)
    return {"preset": preset, "results": results}


# ── review, regen ──

def review(project_dir: str, paths: list[str] | None = None, style_path: str | None = None,
           out: str | None = None) -> list[str]:
    """Review sheets: images on the game's background, audio as waveform + spectrogram."""
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    image_items, audio_items = [], []
    for rel in iter_assets(project, paths):
        if style.ignored(rel):
            continue
        kind = kind_of(rel)
        rule = style.rule_for(rel, kind)
        if kind == "image":
            ok = images.validate_image(project, rel, rule, style)["ok"] if rule else True
            image_items.append({"path": rel, "ok": ok})
        else:
            result = audio.validate_audio(project, rel, rule)
            m = result["metrics"]
            summary = f"{m.get('duration_s')}s  peak {m.get('true_peak_db')} dBFS  " + \
                (f"{m['loudness_lufs']} LUFS" if m.get("loudness_lufs") is not None else f"RMS {m.get('rms_db')} dB")
            audio_items.append({"path": rel, "ok": result["ok"], "summary": summary})
    if not image_items and not audio_items:
        raise GodotAgentError("no assets matched")
    folder = Path(out).expanduser() if out else _out_dir(project, "review")
    sheets = []
    if image_items:
        sheets.append(str(images.review_sheet(image_items, project, folder / "images.png", style.background)))
    if audio_items:
        sheets.append(str(audio.review_sheet(audio_items[:24], project, folder / "audio.png")))
    return sheets


def regen(project_dir: str, path: str, style_path: str | None = None) -> dict:
    """Rebuilds an asset exactly as its manifest entry recorded it."""
    project = resolve_project(project_dir)
    rel = rel_path(project, path)
    entry = manifest.get(project, rel)
    if not entry:
        raise GodotAgentError(f"{rel} has no manifest entry; it was not made by the asset pipeline")
    if entry["tool"] == "sfx":
        return make_sfx(str(project), entry["preset"], rel, seed=entry["seed"], peak_db=entry.get("peak_db", -1.0),
                        params=entry["params"], style_path=style_path)
    if entry["tool"] == "conform":
        return conform(str(project), entry["source"], rel, style_path, **entry["options"])
    if entry["tool"] == "aseprite":
        return import_aseprite(str(project), entry["source"], entry["dest"], style_path)
    raise GodotAgentError(f"unknown tool in manifest: {entry['tool']}")
