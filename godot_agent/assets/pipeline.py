def init_style(project_dir: str, out: str | None = None, force: bool = False) -> dict:
    """Drafts asset_style.json from the assets a project already has.

    Each folder gets a rule describing what its files have in common (size,
    frame grid, alpha, palette, loudness), so new files that break the pattern
    stand out. The draft is a starting point to tighten by hand.
    """
    project = resolve_project(project_dir)
    target = Path(out).expanduser() if out else project / STYLE_FILE
    if target.exists() and not force:
        raise GodotAgentError(f"{target} exists; pass --force to overwrite")
    palette_dir = target.parent / "palettes"
    by_dir: dict[str, list[str]] = collections.defaultdict(list)
    for rel in iter_assets(project):
        by_dir[str(Path(rel).parent)].append(rel)

    rules: list[dict] = []
    palettes: dict[str, str] = {}
    import_votes: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    folder_palettes: dict[str, list] = {}
    image_rules: dict[str, dict] = {}
    for folder, rels in sorted(by_dir.items()):
        image_files = [r for r in rels if kind_of(r) == "image"]
        audio_files = [r for r in rels if kind_of(r) == "audio"]
        if image_files:
            rule, palette = _image_group_rule(project, folder, image_files, import_votes)
            if palette:
                folder_palettes[folder] = palette
            exts = sorted({Path(r).suffix.lstrip(".") for r in image_files})
            pattern = f"{folder}/*.{exts[0]}" if len(exts) == 1 else f"{folder}/*.{{{','.join(exts)}}}"
            image_rules[folder] = rule
            rules.append({"match": pattern, "image": rule, "files": len(image_files)})
        if audio_files:
            rules.append({"match": f"{folder}/*", "audio": _audio_group_rule(project, folder, audio_files),
                          "files": len(audio_files)})
        model_files = [r for r in rels if kind_of(r) == "model"]
        if model_files:
            rules.append({"match": f"{folder}/*.glb" if all(r.endswith(".glb") for r in model_files)
                          else f"{folder}/*.{{glb,gltf}}", "model": _model_group_rule(project, model_files),
                          "files": len(model_files)})

    # Sibling folders (one per animation of a character, say) usually share one
    # palette; give them a single palette file when their colors fit together.
    by_parent: dict[str, list[str]] = collections.defaultdict(list)
    for folder in folder_palettes:
        by_parent[str(Path(folder).parent)].append(folder)
    for parent, siblings in sorted(by_parent.items()):
        union = set().union(*(set(folder_palettes[f]) for f in siblings))
        groups = [(parent, siblings, union)] if len(siblings) > 1 and len(union) <= 64 \
            else [(f, [f], set(folder_palettes[f])) for f in siblings]
        for owner, members, colors in groups:
            slug = re.sub(r"[^A-Za-z0-9]+", "_", owner).strip("_").lower()
            # A folder with its own images and merged subfolders would otherwise
            # write two palettes under one name.
            if len(members) > 1 and owner in folder_palettes:
                slug += "_shared"
            palette_file = palette_dir / f"{slug}.gpl"
            write_palette(palette_file, slug, sorted(colors, key=lambda c: (images.luminance(c), c)))
            palettes[slug] = rel_path(project, palette_file) if palette_file.is_relative_to(project) \
                else str(palette_file)
            for member in members:
                image_rules[member]["palette"] = slug

    general = {key: votes.most_common(1)[0][0] for key, votes in import_votes.items()}
    head = [{"match": "**/*.png", "image": {"import": general}}] if general else []
    style = {"version": 1, "background": default_background(project), "palettes": palettes,
             "ignore": [], "rules": head + rules}
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(style, indent=2) + "\n")
    return {"style": str(target), "rules": len(style["rules"]), "palettes": len(palettes)}


def _image_group_rule(project: Path, folder: str, rels: list[str], import_votes: dict) -> tuple[dict, list]:
    metrics = [images.analyze_image(project / r) for r in rels]
    sizes = collections.Counter(tuple(m["size"]) for m in metrics)
    rule: dict = {}
    top_size, top_count = sizes.most_common(1)[0]
    if top_count / len(rels) >= 0.8 and len(rels) >= 2:
        rule["size"] = list(top_size)
    else:
        grid = 0
        for w, h in sizes:
            grid = math.gcd(grid, math.gcd(w, h))
        heights = {h for _, h in sizes}
        if len(heights) == 1 and all(w % next(iter(heights)) == 0 for w, _ in sizes):
            # One row of square frames per file: an animation strip.
            frame = next(iter(heights))
            rule["frame"] = [frame, frame]
            jitters = [images.analyze_image(project / r, (frame, frame)).get("baseline_jitter", 0) for r in rels]
            rule["max_baseline_jitter"] = max(jitters)
        elif grid >= 8:
            rule["multiple_of"] = [grid, grid]
    if sum(1 for m in metrics if m["semi_transparent_pixels"] == 0) / len(metrics) >= 0.9:
        rule["binary_alpha"] = True
    palette: list = []
    if max(m["colors"] for m in metrics) <= 64:
        union: set = set()
        for r in rels:
            with images.Image.open(project / r) as img:
                union |= {c[:3] for _, c in images._opaque_colors(img.convert("RGBA"))}
        if len(union) <= 64:
            palette = sorted(union, key=lambda c: (images.luminance(c), c))
            rule["max_colors"] = max(m["colors"] for m in metrics)
    contrasts = []
    background = images.hex_to_rgb(default_background(project))
    for m in metrics:
        if m.get("edge_color"):
            contrasts.append(images.contrast_ratio(m["edge_color"], background))
    if contrasts:
        # The weakest existing sprite sets the floor, so new art cannot read worse.
        rule["min_silhouette_contrast"] = math.floor(min(contrasts) * 10) / 10
    for r in rels:
        for key, value in (images.read_import_params(project / r) or {}).items():
            if key in ("compress/mode", "mipmaps/generate"):
                import_votes[key][value] += 1
    return rule, palette


def _level_band(values: list[float]) -> list[float]:
    if len(values) < 3:
        return [round(min(values) - 3, 1), round(max(values) + 3, 1)]
    deciles = statistics.quantiles(values, n=10)
    return [round(deciles[0] - 3, 1), round(deciles[-1] + 3, 1)]


def _audio_group_rule(project: Path, folder: str, rels: list[str]) -> dict:
    looping = any(word in folder.lower() for word in ("bgm", "music", "loop", "ambience"))
    metrics = [audio.analyze_audio(project / r) for r in rels]
    rule: dict = {"max_peak_db": -0.3, "max_leading_silence_ms": 50 if not looping else 250}
    rates = sorted({m["sample_rate"] for m in metrics if m.get("sample_rate")})
    if rates:
        rule["sample_rates"] = rates
    lufs = [m["loudness_lufs"] for m in metrics if m.get("loudness_lufs") is not None]
    rms = [m["rms_db"] for m in metrics if m.get("rms_db") is not None and m.get("loudness_lufs") is None]
    # Files in one folder should sit at a similar level. The 10th to 90th
    # percentile, widened by 3 dB, flags only the ones that jump out of the mix.
    if lufs:
        rule["loudness_lufs"] = _level_band(lufs)
    if rms:
        rule["rms_db"] = _level_band(rms)
    if looping:
        rule["loop"] = True
    else:
        rule["max_duration_s"] = round(max(m.get("duration_s", 0) for m in metrics) + 0.5, 1)
    return rule


def _model_group_rule(project: Path, rels: list[str]) -> dict:
    metrics = [meshes.analyze_model(project / r) for r in rels]
    rule: dict = {"max_tris": int(math.ceil(max(m["tris"] for m in metrics) * 1.25 / 10) * 10)}
    if all(abs(m["min"][1]) <= 0.02 for m in metrics):
        rule["origin"] = "bottom"
    largest = [max(m["size"][i] for m in metrics) for i in range(3)]
    rule["max_size"] = [round(v * 1.5, 2) for v in largest]
    return rule


