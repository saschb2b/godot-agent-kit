# Written by earlier kit versions; replaced by the shader material on the next mesh build.
_OLD_PAINTED_MATERIAL_TRES = """[gd_resource type="StandardMaterial3D" format=3]

[resource]
resource_name = "painted"
vertex_color_use_as_albedo = true
roughness = 1.0
"""
PAINTED_MATERIAL_TRES = """[gd_resource type="ShaderMaterial" load_steps=2 format=3]

[ext_resource type="Shader" path="{shader}" id="1"]

[resource]
resource_name = "painted"
shader = ExtResource("1")
"""
PAINTED_SHADER = Path(__file__).resolve().parent / "templates" / "painted.gdshader"


def _painted_material(project: Path, style: Style) -> str:
    """The shared material that paints generated models (vertex color + pattern shader).

    Creates res://materials/painted.tres and painted.gdshader next to it when
    missing, and refreshes a shader this kit wrote earlier when the template
    changed. A shader the project edited (no kit header) is left alone.
    """
    rel = rel_path(project, style.data.get("model_material", "res://materials/painted.tres"))
    file = project / rel
    shader_rel = Path(rel).with_suffix(".gdshader").as_posix()
    shader_file = project / shader_rel
    template = PAINTED_SHADER.read_text()
    current = shader_file.read_text() if shader_file.exists() else ""
    if not current or (current.startswith("// godot-agent painted") and current.splitlines()[0] != template.splitlines()[0]):
        shader_file.parent.mkdir(parents=True, exist_ok=True)
        shader_file.write_text(template)
    if not file.exists() or file.read_text() == _OLD_PAINTED_MATERIAL_TRES:
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(PAINTED_MATERIAL_TRES.format(shader=f"res://{shader_rel}"))
    return f"res://{rel}"


def _model_import_file(project: Path, rel: str, materials: str | dict) -> None:
    """Points the glTF's materials at the project's, by name: "painted" at the
    vertex-colour material (Godot's glTF importer ignores COLOR_0 for albedo),
    foliage_* at their card materials, and so on.

    Godot keeps these params and fills in the rest on import; an existing uid is
    kept so scenes that reference the model by uid stay valid.
    """
    if isinstance(materials, str):
        materials = {meshes.PAINTED_MATERIAL: materials}
    used = set(meshes.analyze_model(project / rel)["material_names"])
    wanted = {name: path for name, path in sorted(materials.items()) if name in used}
    file = project / f"{rel}.import"
    text = file.read_text() if file.exists() else ""
    if all(f'"use_external/path": "{path}"' in text for path in wanted.values()) and \
            text.count('"use_external/enabled": true') == len(wanted):
        return
    uid = re.search(r'^uid="([^"]+)"', text, re.M)
    lines = ["[remap]", "", 'importer="scene"', 'type="PackedScene"']
    if uid:
        lines.append(f'uid="{uid[1]}"')
    entries = [f'"{name}": {{\n"use_external/enabled": true,\n"use_external/path": "{path}"\n}}'
               for name, path in wanted.items()]
    lines += ["", "[params]", "", "_subresources={", '"materials": {', ",\n".join(entries), "}", "}", ""]
    file.write_text("\n".join(lines))


def make_mesh(project_dir: str, source: str, dest: str, seed: int = 1, variants: int = 1,
              colors: dict | None = None, style_path: str | None = None, recipe: dict | None = None,
              review: bool = False, import_into_godot: bool = True, record: bool = True) -> dict:
    """Builds low-poly .glb models from a preset or recipe file, seeded, in the project's colors.

    Colors resolve in order: the recipe's own, then the style rule's "colors" for the
    destination (so presets pick up the project palette), then `colors` passed here.
    """
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    if recipe is None:
        candidate = Path(source).expanduser()
        if not candidate.exists() and (project / rel_path(project, source)).exists():
            source = str(project / rel_path(project, source))
        label, recipe = meshes.load_recipe(source)
    source_ref = source
    if Path(source).expanduser().exists():
        resolved = Path(source).expanduser().resolve()
        source_ref = resolved.relative_to(project).as_posix() if resolved.is_relative_to(project) else str(resolved)
    rel = rel_path(project, dest)
    if Path(rel).suffix.lower() != ".glb":
        rel = f"{rel[: -len(Path(rel).suffix)] if Path(rel).suffix else rel}.glb"
    material = _painted_material(project, style)
    results, written = [], []
    for n in range(variants):
        variant_seed = seed + n
        out_rel = rel if variants == 1 else f"{rel[:-4]}_{n + 1}.glb"
        rule = style.rule_for(out_rel, "model")
        resolved_recipe = {**recipe, "colors": {**recipe.get("colors", {}), **rule.get("colors", {}),
                                                **(colors or {})}}
        mesh = meshes.build_mesh(resolved_recipe, variant_seed)
        meshes.write_glb(mesh, project / out_rel, Path(out_rel).stem)
        _model_import_file(project, out_rel, {**_existing_material(project, style), "painted": material})
        if record:
            manifest.record(project, out_rel, {"tool": "mesh", "source": source_ref, "seed": variant_seed,
                                               "recipe": resolved_recipe, "license": GENERATED_LICENSE})
        result = meshes.validate_model(project, out_rel, rule, style)
        result["seed"] = variant_seed
        results.append(result)
        written.append(out_rel)
    if import_into_godot:
        godot_import(project)
        if load_errors := _verify_load(project, written):
            results[0]["ok"] = False
            results[0]["problems"] += load_errors
    report = {"source": source_ref, "results": results}
    if review:
        report["preview"] = str(meshes.render_review(project, [_model_item(r) for r in results],
                                                     _out_dir(project, "mesh"), _model_background(style),
                                                     material=_existing_material(project, style)))
    return report


def make_icon(project_dir: str, model: str, dest: str, size: int = 64, pitch: float = 30.0, yaw: float = 35.0,
              frame: dict | None = None, style_path: str | None = None, import_into_godot: bool = True,
              record: bool = True) -> dict:
    """Renders a 3D model to a transparent PNG icon (command cards, inventories, portraits)."""
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    source = Path(model).expanduser()
    if not source.is_absolute():
        source = project / rel_path(project, model)
    if not source.exists():
        raise GodotAgentError(f"No model at {source}")
    rel = rel_path(project, dest)
    rendered = meshes.render_icons(project, [source], _out_dir(project, "icon"), size=size, pitch=pitch, yaw=yaw,
                                   material=_existing_material(project, style), frame=frame)[0]
    target = project / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(rendered.read_bytes())
    if record:
        model_ref = source.resolve().relative_to(project).as_posix() if source.resolve().is_relative_to(project) \
            else str(source.resolve())
        manifest.record(project, rel, {"tool": "icon", "model": model_ref, "size": size, "pitch": pitch, "yaw": yaw,
                                       "frame": frame, "license": "same as the model"})
    if import_into_godot:
        godot_import(project)
    report = images.validate_image(project, rel, style.rule_for(rel, "image"), style)
    report["preview"] = str(rendered)
    return report


# ── Terrain textures ──

def make_texture(project_dir: str, preset: str, dest: str, size: int = 256, seed: int = 1,
                 colors: dict | None = None, style_path: str | None = None, import_into_godot: bool = True,
                 record: bool = True) -> dict:
    """Paints a seamless terrain texture (grass, meadow, path, dirt, sand, mud, rock, cobble).

    Also writes its .import with mipmaps on, since terrain is seen at a slant and
    from far away, where an unmipmapped texture shimmers.
    """
    from . import textures
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    rel = rel_path(project, dest)
    if Path(rel).suffix.lower() != ".png":
        rel = f"{rel[: -len(Path(rel).suffix)] if Path(rel).suffix else rel}.png"
    rule = style.rule_for(rel, "image")
    merged = {**rule.get("colors", {}), **(colors or {})}
    card = preset in textures.CARDS
    image = textures.paint_card(preset, size, seed) if card else textures.paint(preset, size, seed, merged)
    target = project / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    image.save(target, optimize=True)
    import_file = project / f"{rel}.import"
    if not import_file.exists():
        import_file.write_text(textures.IMPORT_FILE)
    if card:
        # A foliage card gets its material: res://materials/<preset>.tres over the
        # kit's foliage shader, which models' foliage_* materials are mapped to.
        _install_template(project, "foliage.gdshader", "// godot-agent foliage")
        (project / "materials" / f"{Path(rel).stem}.tres").write_text(FOLIAGE_MATERIAL_TRES.format(
            name=Path(rel).stem, texture=f"res://{rel}"))
    if record:
        manifest.record(project, rel, {"tool": "texture", "preset": preset, "size": size, "seed": seed,
                                       "colors": merged, "license": GENERATED_LICENSE})
    if import_into_godot:
        godot_import(project)
    report = images.validate_image(project, rel, rule, style)
    sheet = _out_dir(project, "texture") / "tiled.png"
    tiled = images.Image.new("RGBA" if card else "RGB", (size * 2, size * 2))
    for dx in (0, size):
        for dy in (0, size):
            tiled.paste(image, (dx, dy))
    tiled.save(sheet)
    report["preview"] = str(sheet)
    return report


FOLIAGE_MATERIAL_TRES = """[gd_resource type="ShaderMaterial" load_steps=3 format=3]

[ext_resource type="Shader" path="res://materials/foliage.gdshader" id="1"]
[ext_resource type="Texture2D" path="{texture}" id="2"]

[resource]
resource_name = "{name}"
shader = ExtResource("1")
shader_parameter/albedo_tex = ExtResource("2")
"""


def _install_template(project: Path, name: str, header: str) -> None:
    """Copies a kit shader into res://materials/, refreshing it while it still carries
    the kit's header (a project's own edits, without the header, are kept)."""
    template = (Path(__file__).resolve().parent / "templates" / name).read_text()
    target = project / "materials" / name
    current = target.read_text() if target.exists() else ""
    if not current or (current.startswith(header) and current.splitlines()[0] != template.splitlines()[0]):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(template)


# ── Blender models ──

def make_blender(project_dir: str, script: str, dest: str, seed: int = 1, params: dict | None = None,
                 style_path: str | None = None, review: bool = False, import_into_godot: bool = True,
                 record: bool = True, timeout: int = 600) -> dict:
    """Runs a Blender build script headless and exports its scene to dest (.glb).

    The script builds a model with the kit's `gab` helpers (godot_agent/blender/gab.py).
    Materials map to the project's by name, the recipe (script, seed, params) is
    recorded for `asset regen`, and the model is checked like any other.
    """
    import shutil
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    blender = shutil.which("blender")
    if not blender:
        raise GodotAgentError("blender not found on PATH")
    source = Path(script).expanduser()
    if not source.is_absolute():
        source = (project / rel_path(project, script)) if (project / rel_path(project, script)).exists() \
            else source.resolve()
    if not source.exists():
        raise GodotAgentError(f"No build script at {source}")
    rel = rel_path(project, dest)
    if Path(rel).suffix.lower() != ".glb":
        rel = f"{rel[: -len(Path(rel).suffix)] if Path(rel).suffix else rel}.glb"
    target = project / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    runner = Path(__file__).resolve().parent.parent / "blender" / "runner.py"
    cmd = [blender, "-b", "--factory-startup", "--python-exit-code", "1", "-P", str(runner), "--",
           "--script", str(source), "--out", str(target), "--seed", str(seed),
           "--params", json.dumps(params or {})]
    from ..runner import render_slot
    with render_slot():  # (a Blender build holds as much memory as a rendered Godot run)
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if proc.returncode != 0 or not target.exists():
        log = (proc.stdout + proc.stderr).strip().splitlines()
        errors = [line for line in log if "Error" in line or "Traceback" in line or line.startswith("  File")]
        raise GodotAgentError("blender build failed:\n" + "\n".join((errors or log)[-25:]))
    _painted_material(project, style)
    _model_import_file(project, rel, _existing_material(project, style))
    script_ref = source.resolve().relative_to(project).as_posix() if source.resolve().is_relative_to(project) \
        else str(source.resolve())
    if record:
        manifest.record(project, rel, {"tool": "blender", "script": script_ref, "seed": seed, "params": params or {},
                                       "license": GENERATED_LICENSE})
    report = meshes.validate_model(project, rel, style.rule_for(rel, "model"), style)
    report["notes"].append(next((l for l in proc.stdout.splitlines() if l.startswith("godot-agent: exported")),
                                "exported"))
    if import_into_godot:
        godot_import(project)
        if load_errors := _verify_load(project, [rel]):
            report["ok"] = False
            report["problems"] += load_errors
    if review:
        report["preview"] = str(meshes.render_review(project, [_model_item(report)], _out_dir(project, "blender"),
                                                     _model_background(style), material=_existing_material(project, style)))
    return report


# ── UI frames ──

def make_ui(project_dir: str, preset: str, dest: str, size: list[int], fill: str = "stone", trim: str = "gold",
            fill_color: str | None = None, border: int | None = None, seed: int = 1, spec: str | None = None,
            import_into_godot: bool = True, record: bool = True) -> dict:
    """Paints a nine-slice UI piece (panel, bar, tooltip, button states, slot, frame) and its StyleBoxTexture,
    or with preset "console" every piece of a bottom console described by the JSON `spec`, into the folder `dest`."""
    from . import ui
    project = resolve_project(project_dir)
    rel = rel_path(project, dest)
    rel = rel[: -len(Path(rel).suffix)] if Path(rel).suffix in (".png", ".tres") else rel
    options = {"fill": fill, "trim": trim, "fill_color": fill_color, "border": border, "seed": seed}
    paint_options = dict(options)
    if preset == "console":
        if not spec:
            raise GodotAgentError("the console preset needs --spec, a JSON file such as art_src/ui/console.json")
        spec_file = Path(spec).expanduser()
        if not spec_file.is_absolute():
            spec_file = project / rel_path(project, spec)
        if not spec_file.exists():
            raise GodotAgentError(f"No console spec at {spec_file}")
        # The console takes everything from its spec: record only that, for regen.
        options = {"spec": spec_file.resolve().relative_to(project).as_posix()
                   if spec_file.resolve().is_relative_to(project) else str(spec_file.resolve())}
        paint_options = {"spec": json.loads(spec_file.read_text())}
    written = ui.write(preset, project / rel, f"res://{rel}", tuple(size), **paint_options)
    rels = [w.relative_to(project).as_posix() for w in written]
    if record:
        for out in rels:
            manifest.record(project, out, {"tool": "ui", "preset": preset, "dest": rel, "size": list(size),
                                           "options": options, "license": GENERATED_LICENSE})
    if import_into_godot:
        godot_import(project)
        if load_errors := _verify_load(project, [r for r in rels if r.endswith(".tres")]):
            return {"path": rel, "ok": False, "problems": load_errors, "files": rels}
    sheet = _out_dir(project, "ui") / "ui.png"
    images.review_sheet([{"path": r, "ok": True} for r in rels if r.endswith(".png")], project, sheet,
                        "#202020", tile=min(256, max(size)))
    return {"path": rel, "ok": True, "problems": [], "notes": [], "files": rels, "preview": str(sheet)}


# ── review, regen ──

def review(project_dir: str, paths: list[str] | None = None, style_path: str | None = None,
           out: str | None = None) -> list[str]:
    """Review sheets: images on the game's background, audio as waveform + spectrogram."""
    project = resolve_project(project_dir)
    style = Style.load(project, style_path)
    image_items, audio_items, model_items = [], [], []
    for rel in iter_assets(project, paths):
        if style.ignored(rel):
            continue
        kind = kind_of(rel)
        rule = style.rule_for(rel, kind)
        if kind == "image":
            ok = images.validate_image(project, rel, rule, style)["ok"] if rule else True
            image_items.append({"path": rel, "ok": ok})
        elif kind == "model":
            model_items.append(_model_item(meshes.validate_model(project, rel, rule, style)))
        else:
            result = audio.validate_audio(project, rel, rule)
            m = result["metrics"]
            summary = f"{m.get('duration_s')}s  peak {m.get('true_peak_db')} dBFS  " + \
                (f"{m['loudness_lufs']} LUFS" if m.get("loudness_lufs") is not None else f"RMS {m.get('rms_db')} dB")
            audio_items.append({"path": rel, "ok": result["ok"], "summary": summary})
    if not image_items and not audio_items and not model_items:
        raise GodotAgentError("no assets matched")
    folder = Path(out).expanduser() if out else _out_dir(project, "review")
    sheets = []
    if image_items:
        sheets.append(str(images.review_sheet(image_items, project, folder / "images.png", style.background)))
    if audio_items:
        sheets.append(str(audio.review_sheet(audio_items[:24], project, folder / "audio.png")))
    if model_items:
        sheets.append(str(meshes.render_review(project, model_items[:16], folder / "models",
                                               _model_background(style), material=_existing_material(project, style))))
    return sheets


def regen(project_dir: str, path: str, style_path: str | None = None) -> dict:
    """Rebuilds an asset exactly as its manifest entry recorded it."""
    project = resolve_project(project_dir)
    rel = rel_path(project, path)
    entry = manifest.get(project, rel)
    if not entry:
        raise GodotAgentError(f"{rel} has no manifest entry; it was not made by the asset pipeline")
    if entry["tool"] == "sfx":
        return make_sfx(str(project), entry["preset"], rel, seed=entry["seed"], peak_db=entry.get("peak_db", -1.0),
                        params=entry["params"], style_path=style_path)
    if entry["tool"] == "conform":
        return conform(str(project), entry["source"], rel, style_path, **entry["options"])
    if entry["tool"] == "mesh":
        return make_mesh(str(project), entry["source"], rel, seed=entry["seed"], recipe=entry["recipe"],
                         style_path=style_path)
    if entry["tool"] == "blender":
        return make_blender(str(project), entry["script"], rel, seed=entry["seed"], params=entry.get("params"),
                            style_path=style_path)
    if entry["tool"] == "texture":
        return make_texture(str(project), entry["preset"], rel, size=entry["size"], seed=entry["seed"],
                            colors=entry.get("colors"), style_path=style_path)
    if entry["tool"] == "ui":
        return make_ui(str(project), entry["preset"], entry["dest"], entry["size"], **entry["options"])
    if entry["tool"] == "icon":
        return make_icon(str(project), entry["model"], rel, size=entry["size"], pitch=entry["pitch"],
                         yaw=entry["yaw"], frame=entry.get("frame"), style_path=style_path)
    if entry["tool"] == "aseprite":
        return import_aseprite(str(project), entry["source"], entry["dest"], style_path)
    if entry["tool"] == "script":
        return _regen_script(project, rel, entry)
    raise GodotAgentError(f"unknown tool in manifest: {entry['tool']}")


def _regen_script(project: Path, rel: str, entry: dict) -> dict:
    """Reruns the project's own generator for a file, e.g. a Pillow painter under art_src/ recorded as
    {"tool": "script", "regen": "python3 art_src/ui/console.py ..."}. It runs in the project folder, without a
    shell, and must rewrite the file."""
    command = shlex.split(entry.get("regen", ""))
    if not command:
        raise GodotAgentError(f"{rel}: a script entry needs a \"regen\" command")
    before = (project / rel).stat().st_mtime_ns if (project / rel).exists() else None
    proc = subprocess.run(command, cwd=project, capture_output=True, text=True)
    if proc.returncode != 0:
        tail = (proc.stderr or proc.stdout).strip().splitlines()[-5:]
        return {"path": rel, "ok": False, "problems": [f"{entry['regen']} exited {proc.returncode}", *tail]}
    if not (project / rel).exists() or (project / rel).stat().st_mtime_ns == before:
        return {"path": rel, "ok": False, "problems": [f"{entry['regen']} did not write {rel}"]}
    godot_import(project)
    return {"path": rel, "ok": True, "problems": [], "notes": [], "steps": [entry["regen"]]}
